import type {
  Diagnostic,
  FixResult,
  Reporter,
  ScanResult,
  Transformation,
  Workspace,
} from '@tailwind-refactor/plugin-api';
import { FileSystemWorkspace } from './workspace.js';

/**
 * Minimal structural shape of the config accepted by PipelineOptions.
 * Structurally compatible with `TailwindRefactorConfig` from `@tailwind-refactor/config`,
 * which sits above `core` in the dependency graph and cannot be imported here.
 */
export interface PipelineConfig {
  rules?: Record<string, 'off' | 'warn' | 'error'>;
  ignore?: string[];
  confidenceThreshold?: 'safe' | 'suggestion' | 'experimental';
  tailwindVersion?: 'v3' | 'v4' | 'auto';
  extends?: string | string[];
}

/**
 * Minimal structural shape of an ignore context accepted by PipelineOptions.
 * Structurally compatible with `IgnoreContext` from `@tailwind-refactor/ignore`.
 */
export interface PipelineIgnoreContext {
  isFileIgnored(filePath: string): boolean;
}

/**
 * Minimal structural interface for the RefactorEngine, used by PipelineOptions.
 * Defined here to avoid a circular import with `@tailwind-refactor/rules`.
 */
export interface RefactorEngineInterface {
  analyzeCode(code: string, filePath?: string): Transformation[];
  analyzeCodeWithAnalysis(
    code: string,
    filePath?: string
  ): { transformations: Transformation[]; dynamicCandidates: { line?: number; reason?: string; expression: string }[] };
  patchCode(code: string, transformations: Transformation[]): string;
}

/**
 * Options for controlling a single `scan()` or `fix()` pipeline execution.
 *
 * @remarks
 * All fields are optional. When omitted, sensible defaults are used
 * (`dir: 'src'`, `dryRun: false`, `FileSystemWorkspace` etc.).
 *
 * @see {@link RefactorPipeline.scan}
 * @see {@link RefactorPipeline.fix}
 */
export interface PipelineOptions {
  /**
   * Root directory to scan relative to the workspace root.
   * @default `'src'`
   */
  dir?: string;
  /**
   * Absolute path to the project root. Used for config resolution.
   * @default `process.cwd()`
   */
  cwd?: string;
  /** Explicit path to a `tailwind-refactor.config.ts` configuration file. */
  configPath?: string;
  /** Additional glob pattern to ignore (e.g. `'**\/generated\/**'`). */
  ignorePattern?: string;
  /**
   * If `true`, distributes file analysis across Node.js `worker_threads`.
   * Recommended for projects with 1,000+ source files.
   */
  parallel?: boolean;
  /**
   * If `true`, no files are modified on disk during `fix()`.
   * The returned `FixResult` will still report what *would* have changed.
   */
  dryRun?: boolean;
  /**
   * A custom {@link Reporter} to format and emit the scan result.
   * If omitted, no output is generated by the pipeline itself.
   */
  reporter?: Reporter;
  /**
   * An instance of `RefactorEngine` to use for analysis.
   * If omitted, files are globbed but no rule evaluation is performed.
   */
  engine?: RefactorEngineInterface;
  /** The resolved configuration object for the current workspace. */
  config?: PipelineConfig;
  /** The active ignore context (inline ignores + config ignores combined). */
  ignoreContext?: PipelineIgnoreContext;
  /** Callback for progress reporting during scan or fix. */
  onProgress?: (processed: number, total: number, file: string) => void;
}

/**
 * Central unified execution pipeline for all tailwind-refactor operations.
 *
 * @description
 * `RefactorPipeline` is the **single point of execution** for every consumer:
 * - The CLI (`tailwind-refactor scan`, `tailwind-refactor fix`)
 * - The programmatic Node.js SDK (`scan()`, `fix()`)
 * - The VS Code extension (inline quick-fix diagnostics)
 * - The ESLint plugin (per-file rule evaluation)
 * - The GitHub Action (SARIF report generation)
 *
 * This design guarantees **zero logic drift** between consumers — every
 * integration exercises the same parsing, ignore checking, rule evaluation,
 * collision detection, and patch application code path.
 *
 * @remarks
 * The pipeline is workspace-agnostic by design. Passing a {@link MemoryWorkspace}
 * makes the entire pipeline runnable in-memory without any disk access,
 * enabling fast isolated unit tests and the browser REPL playground.
 *
 * **Internal execution lifecycle** for `scan()`:
 * ```
 * Workspace.glob()
 *   → Workspace.readFile()
 *     → engine.analyzeCodeWithAnalysis()
 *       → collect Transformations + Diagnostics
 *   → assemble ScanResult
 * ```
 *
 * **Internal execution lifecycle** for `fix()`:
 * ```
 * Workspace.glob()
 *   → Workspace.readFile()
 *     → engine.analyzeCode()
 *       → engine.patchCode()
 *         → Workspace.writeFile()
 * ```
 *
 * @example
 * // In-memory pipeline (for unit tests or browser REPL)
 * const ws = new MemoryWorkspace({ 'src/Button.tsx': '<div className="h-[40px]" />' });
 * const pipeline = new RefactorPipeline(ws);
 * const result = await pipeline.scan({ dir: 'src', engine: myEngine });
 *
 * @example
 * // Production disk-backed pipeline
 * const pipeline = new RefactorPipeline();
 * const result = await pipeline.scan({ dir: 'src', engine: myEngine });
 *
 * @see {@link FileSystemWorkspace}
 * @see {@link MemoryWorkspace}
 * @see {@link PipelineOptions}
 */
export class RefactorPipeline {
  /** The workspace backing this pipeline instance. */
  private workspace: Workspace;

  /**
   * Creates a new `RefactorPipeline`.
   * @param workspace - The workspace implementation to use for file I/O.
   *                    Defaults to a {@link FileSystemWorkspace} for the current `process.cwd()`.
   */
  constructor(workspace?: Workspace) {
    this.workspace = workspace ?? new FileSystemWorkspace();
  }

  /**
   * Returns the active workspace instance for this pipeline.
   * Useful for testing or inspecting file state after a fix operation.
   * @returns The {@link Workspace} instance backing this pipeline.
   */
  public getWorkspace(): Workspace {
    return this.workspace;
  }

  /**
   * Scans all source files in the target directory and returns a complete {@link ScanResult}.
   *
   * @description
   * Globs all supported source files (`*.ts`, `*.tsx`, `*.js`, `*.jsx`,
   * `*.vue`, `*.svelte`, `*.astro`, `*.html`) under `options.dir`,
   * runs rule evaluation via `options.engine`, and collects all
   * {@link Transformation}s and {@link Diagnostic}s.
   *
   * @param options - Pipeline execution options. See {@link PipelineOptions}.
   * @returns A {@link ScanResult} aggregating all findings across the workspace.
   *
   * @example
   * const result = await pipeline.scan({ dir: 'src', engine: refactorEngine });
   * console.log(`Found ${result.totalTransformations} issues in ${result.filesScanned} files.`);
   */
  public async scan(options: PipelineOptions = {}): Promise<ScanResult> {
    const startTime = Date.now();
    const targetDir = options.dir || 'src';
    const pattern = `${targetDir}/**/*.{ts,tsx,js,jsx,vue,svelte,astro,html}`;

    const defaultIgnores = [
      '**/node_modules/**',
      '**/dist/**',
      '**/.next/**',
      '**/.turbo/**',
      '**/build/**',
      '**/.cache/**',
      '**/.git/**',
      '**/*.min.js',
    ];

    const rawFiles = await this.workspace.glob(pattern, {
      ignore: options.ignorePattern ? [options.ignorePattern, ...defaultIgnores] : defaultIgnores,
    });

    const files = rawFiles.filter((filePath) => {
      const norm = filePath.replace(/\\/g, '/');
      return !(
        norm.includes('/node_modules/') ||
        norm.includes('/dist/') ||
        norm.includes('/.next/') ||
        norm.includes('/.turbo/') ||
        norm.includes('/build/') ||
        norm.includes('/.cache/') ||
        norm.includes('/.git/') ||
        norm.endsWith('.min.js')
      );
    });

    const transformations: Transformation[] = [];
    const diagnostics: Diagnostic[] = [];
    const fileReports: { file: string; count: number; items: Transformation[] }[] = [];

    // Execute engine scan
    const engine = options.engine;
    if (engine) {
      let processed = 0;
      for (const filePath of files) {
        try {
          const rawCode = await this.workspace.readFile(filePath);
          const hasCRLF = rawCode.includes('\r\n');
          const code = hasCRLF ? rawCode.replace(/\r\n/g, '\n') : rawCode;
          const analysis = engine.analyzeCodeWithAnalysis(code, filePath);

          if (analysis.transformations.length > 0) {
            transformations.push(...(analysis.transformations as Transformation[]));
            fileReports.push({
              file: filePath,
              count: analysis.transformations.length,
              items: analysis.transformations as Transformation[],
            });
          }

          for (const dyn of analysis.dynamicCandidates) {
            diagnostics.push({
              code: 'DYNAMIC_VALUE_SKIPPED',
              message: dyn.reason || 'Runtime interpolated value skipped',
              severity: 'info',
              file: filePath,
              line: dyn.line,
            });
          }
        } catch (err: unknown) {
          const message = err instanceof Error ? err.message : String(err);
          diagnostics.push({
            code: 'FILE_READ_ERROR',
            message,
            severity: 'error',
            file: filePath,
          });
        }
        processed++;
        options.onProgress?.(processed, files.length, filePath);
      }
    }

    const result: ScanResult = {
      filesScanned: files.length,
      filesIgnored: 0,
      totalTransformations: transformations.length,
      transformations,
      diagnostics,
      fileReports,
      durationMs: Date.now() - startTime,
    };

    return result;
  }

  /**
   * Scans and applies all safe transformations to source files in the target directory.
   *
   * @description
   * Behaves identically to `scan()` for rule evaluation, but additionally writes
   * patched source code back to the workspace via `engine.patchCode()` and
   * `workspace.writeFile()`.
   *
   * When `options.dryRun` is `true`, no files are written to the workspace.
   * The returned {@link FixResult} still accurately reports what *would* have changed.
   *
   * @param options - Pipeline execution options. See {@link PipelineOptions}.
   * @returns A {@link FixResult} summarizing how many files and transformations were applied.
   *
   * @example
   * // Dry run: preview changes without writing
   * const result = await pipeline.fix({ dir: 'src', engine, dryRun: true });
   * console.log(`Would fix ${result.totalTransformationsApplied} issues.`);
   *
   * @example
   * // Live fix: write patched files to disk
   * const result = await pipeline.fix({ dir: 'src', engine });
   * console.log(`Fixed ${result.filesFixed} files.`);
   */
  public async fix(options: PipelineOptions = {}): Promise<FixResult> {
    const startTime = Date.now();
    const targetDir = options.dir || 'src';
    const pattern = `${targetDir}/**/*.{ts,tsx,js,jsx,vue,svelte,astro,html}`;

    const defaultIgnores = [
      '**/node_modules/**',
      '**/dist/**',
      '**/.next/**',
      '**/.turbo/**',
      '**/build/**',
      '**/.cache/**',
      '**/.git/**',
      '**/*.min.js',
    ];

    const rawFiles = await this.workspace.glob(pattern, {
      ignore: options.ignorePattern ? [options.ignorePattern, ...defaultIgnores] : defaultIgnores,
    });

    const files = rawFiles.filter((filePath) => {
      const norm = filePath.replace(/\\/g, '/');
      return !(
        norm.includes('/node_modules/') ||
        norm.includes('/dist/') ||
        norm.includes('/.next/') ||
        norm.includes('/.turbo/') ||
        norm.includes('/build/') ||
        norm.includes('/.cache/') ||
        norm.includes('/.git/') ||
        norm.endsWith('.min.js')
      );
    });

    let filesFixed = 0;
    let totalTransformationsApplied = 0;
    const engine = options.engine;

    if (engine) {
      let processed = 0;
      for (const filePath of files) {
        try {
          const rawCode = await this.workspace.readFile(filePath);
          const hasCRLF = rawCode.includes('\r\n');
          const code = hasCRLF ? rawCode.replace(/\r\n/g, '\n') : rawCode;
          const analysis = engine.analyzeCode(code, filePath);

          if (analysis.length > 0) {
            if (!options.dryRun) {
              const patched = engine.patchCode(code, analysis);
              const finalCode = hasCRLF ? patched.replace(/\n/g, '\r\n') : patched;
              await this.workspace.writeFile(filePath, finalCode);
            }
            filesFixed++;
            totalTransformationsApplied += analysis.length;
          }
        } catch {
          // Skip file error
        }
        processed++;
        options.onProgress?.(processed, files.length, filePath);
      }
    }

    return {
      filesFixed,
      totalTransformationsApplied,
      isDryRun: !!options.dryRun,
      durationMs: Date.now() - startTime,
    };
  }
}
